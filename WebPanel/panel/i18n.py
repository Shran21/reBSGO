def pick_lang(cookie_value, default: str) -> str:
    return cookie_value if cookie_value in LANGS else (default if default in LANGS else "hu")


def translator(lang: str):
    table = STRINGS.get(lang, STRINGS["hu"])
    fallback = STRINGS["hu"]

    def t(key: str) -> str:
        return table.get(key) or fallback.get(key) or key
    return t
